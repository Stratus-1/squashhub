// Bundles the shared tournament engine for the auto-progress-tournaments edge function.
// The browser Supabase client is swapped for a server shim (client injected at runtime).
// Run: bun scripts/build-auto-progress.ts
const shim = `const c=()=>{const x=globalThis.__shServerClient;if(!x)throw new Error("server client not set");return x;};
export const supabase={from:(...a)=>c().from(...a),rpc:(...a)=>c().rpc(...a),channel:(...a)=>c().channel(...a),removeChannel:(...a)=>c().removeChannel(...a),auth:{getUser:async()=>({data:{user:null},error:null}),getSession:async()=>({data:{session:null},error:null})},functions:{invoke:(...a)=>c().functions.invoke(...a)},storage:{from:(...a)=>c().storage.from(...a)}};`;
const r = await Bun.build({
  entrypoints: ["src/lib/tournaments/server-engine-entry.ts"], target: "browser", format: "esm", minify: false,
  plugins: [{ name: "server-client", setup(b) {
    b.onResolve({ filter: /^@\/integrations\/supabase\/client$/ }, () => ({ path: "sb-shim", namespace: "shim" }));
    b.onLoad({ filter: /.*/, namespace: "shim" }, () => ({ contents: shim, loader: "js" }));
  } }],
});
if (!r.success) { console.error(r.logs); process.exit(1); }
const code = "// GENERATED by scripts/build-auto-progress.ts — do not edit.\n// deno-lint-ignore-file\n" + await r.outputs[0].text();
await Bun.write("supabase/functions/auto-progress-tournaments/engine.js", code);
console.log("ok", code.length);
